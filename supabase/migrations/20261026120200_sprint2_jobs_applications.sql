-- Sprint 2 / Migration 3 of 3: jobs and applications
--
-- Matches the SQL already written in the backend:
--   * GET /api/jobs, /api/jobs/<id>          (app.py)
--   * POST /api/applications                 (application_submission.py)
--   * GET /api/applications, PATCH status    (application_tracking.py)
--   * /api/recruiter/jobs                    (recruiter_postings.py, Parsa)
