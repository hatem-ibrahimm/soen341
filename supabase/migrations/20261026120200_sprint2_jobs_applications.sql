BEGIN;

-- ---------------------------------------------------------------------------
-- 1. Jobs
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recruiter_id uuid NOT NULL
    REFERENCES auth.users(id) ON DELETE CASCADE,
  title text NOT NULL CHECK (length(trim(title)) > 0),
  company_name text NOT NULL CHECK (length(trim(company_name)) > 0),
  location text NOT NULL CHECK (length(trim(location)) > 0),
  category text NOT NULL CHECK (length(trim(category)) > 0),
  description text NOT NULL CHECK (length(trim(description)) > 0),
  required_skills text[] NOT NULL DEFAULT '{}',
  min_salary numeric CHECK (min_salary >= 0),
  max_salary numeric CHECK (max_salary >= 0),
  status text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'published', 'closed')),
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),

  CONSTRAINT jobs_salary_range
    CHECK (min_salary IS NULL OR max_salary IS NULL OR max_salary >= min_salary)
);

CREATE INDEX IF NOT EXISTS jobs_recruiter_id_idx
  ON public.jobs (recruiter_id);
-- job search: published jobs, newest first
CREATE INDEX IF NOT EXISTS jobs_published_idx
  ON public.jobs (created_at DESC) WHERE status = 'published';
CREATE INDEX IF NOT EXISTS jobs_category_idx
  ON public.jobs (lower(category));
CREATE INDEX IF NOT EXISTS jobs_location_idx
  ON public.jobs (lower(location));
CREATE INDEX IF NOT EXISTS jobs_salary_idx
  ON public.jobs (min_salary, max_salary);

DROP TRIGGER IF EXISTS set_jobs_updated_at ON public.jobs;
CREATE TRIGGER set_jobs_updated_at
  BEFORE UPDATE ON public.jobs
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ---------------------------------------------------------------------------
-- 2. Applications
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.applications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  applicant_id uuid NOT NULL
    REFERENCES auth.users(id) ON DELETE CASCADE,
  job_id bigint NOT NULL
    REFERENCES public.jobs(id) ON DELETE CASCADE,
  resume_id uuid
    REFERENCES public.resumes(id) ON DELETE SET NULL,
  cover_letter text CHECK (cover_letter IS NULL OR length(cover_letter) <= 2000),
  status text NOT NULL DEFAULT 'Applied'
    CHECK (status IN ('Applied', 'Under Review', 'Interview', 'Offered', 'Rejected')),
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),

  -- one application per person per job (the backend returns 409 on this)
  CONSTRAINT applications_applicant_job_key UNIQUE (applicant_id, job_id)
);

CREATE INDEX IF NOT EXISTS applications_job_id_idx
  ON public.applications (job_id);
CREATE INDEX IF NOT EXISTS applications_applicant_idx
  ON public.applications (applicant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS applications_status_idx
  ON public.applications (status);

DROP TRIGGER IF EXISTS set_applications_updated_at ON public.applications;
CREATE TRIGGER set_applications_updated_at
  BEFORE UPDATE ON public.applications
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ---------------------------------------------------------------------------
-- 3. Row Level Security
-- ---------------------------------------------------------------------------
-- The Flask backend connects with DATABASE_URL, which normally bypasses these
-- rules, so the backend must keep checking ownership itself (it does). These
-- policies protect the tables if anything ever talks to them directly.

ALTER TABLE public.jobs         ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.applications ENABLE ROW LEVEL SECURITY;

-- Anyone may read published jobs; a recruiter also sees their own drafts.
DROP POLICY IF EXISTS jobs_select_visible ON public.jobs;
CREATE POLICY jobs_select_visible
  ON public.jobs FOR SELECT TO anon, authenticated
  USING (status = 'published' OR recruiter_id = (SELECT auth.uid()));

DROP POLICY IF EXISTS jobs_insert_own ON public.jobs;
CREATE POLICY jobs_insert_own
  ON public.jobs FOR INSERT TO authenticated
  WITH CHECK (
    recruiter_id = (SELECT auth.uid())
    AND (SELECT auth.jwt() -> 'app_metadata' ->> 'role') = 'recruiter'
  );

DROP POLICY IF EXISTS jobs_update_own ON public.jobs;
CREATE POLICY jobs_update_own
  ON public.jobs FOR UPDATE TO authenticated
  USING (recruiter_id = (SELECT auth.uid()))
  WITH CHECK (recruiter_id = (SELECT auth.uid()));

DROP POLICY IF EXISTS jobs_delete_own ON public.jobs;
CREATE POLICY jobs_delete_own
  ON public.jobs FOR DELETE TO authenticated
  USING (recruiter_id = (SELECT auth.uid()));

-- Applicants see and create their own applications and may withdraw them.
DROP POLICY IF EXISTS applications_select_own ON public.applications;
CREATE POLICY applications_select_own
  ON public.applications FOR SELECT TO authenticated
  USING (applicant_id = (SELECT auth.uid()));

DROP POLICY IF EXISTS applications_insert_own ON public.applications;
CREATE POLICY applications_insert_own
  ON public.applications FOR INSERT TO authenticated
  WITH CHECK (
    applicant_id = (SELECT auth.uid())
    AND status = 'Applied'
    AND EXISTS (
      SELECT 1 FROM public.jobs AS j
      WHERE j.id = job_id AND j.status = 'published'
    )
  );

DROP POLICY IF EXISTS applications_delete_own ON public.applications;
CREATE POLICY applications_delete_own
  ON public.applications FOR DELETE TO authenticated
  USING (applicant_id = (SELECT auth.uid()));

-- A recruiter sees and updates the status of applications to THEIR jobs.
DROP POLICY IF EXISTS applications_select_recruiter ON public.applications;
CREATE POLICY applications_select_recruiter
  ON public.applications FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.jobs AS j
      WHERE j.id = job_id AND j.recruiter_id = (SELECT auth.uid())
    )
  );

DROP POLICY IF EXISTS applications_update_recruiter ON public.applications;
CREATE POLICY applications_update_recruiter
  ON public.applications FOR UPDATE TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.jobs AS j
      WHERE j.id = job_id AND j.recruiter_id = (SELECT auth.uid())
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.jobs AS j
      WHERE j.id = job_id AND j.recruiter_id = (SELECT auth.uid())
    )
  );

GRANT SELECT ON TABLE public.jobs TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.jobs         TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.applications TO authenticated;

COMMENT ON TABLE public.jobs IS
  'Job postings. status: draft (hidden), published (searchable), closed.';
COMMENT ON TABLE public.applications IS
  'A job seeker''s application to a job. status: Applied, Under Review, Interview, Offered, Rejected.';

COMMIT;
