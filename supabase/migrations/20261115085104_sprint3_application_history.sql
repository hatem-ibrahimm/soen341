-- Sprint 3: application analytics and history dashboard
-- Keeps a record of every status an application goes through, so the
-- dashboard can show a timeline and stats per job seeker.

CREATE TABLE IF NOT EXISTS public.application_status_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id uuid NOT NULL REFERENCES public.applications(id) ON DELETE CASCADE,
  old_status text,
  new_status text NOT NULL,
  changed_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS application_status_history_app_idx
  ON public.application_status_history (application_id, changed_at);

-- add a history row when an application is created or its status changes
CREATE OR REPLACE FUNCTION public.log_application_status()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.application_status_history (application_id, old_status, new_status)
    VALUES (NEW.id, NULL, NEW.status);
  ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO public.application_status_history (application_id, old_status, new_status)
    VALUES (NEW.id, OLD.status, NEW.status);
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS log_application_status ON public.applications;
CREATE TRIGGER log_application_status
  AFTER INSERT OR UPDATE OF status ON public.applications
  FOR EACH ROW EXECUTE FUNCTION public.log_application_status();

-- applications that already exist get their current status as a first entry
INSERT INTO public.application_status_history (application_id, old_status, new_status, changed_at)
SELECT a.id, NULL, a.status, a.created_at
FROM public.applications AS a
WHERE NOT EXISTS (
  SELECT 1 FROM public.application_status_history AS h WHERE h.application_id = a.id
);

ALTER TABLE public.application_status_history ENABLE ROW LEVEL SECURITY;

-- read only: the applicant, and the recruiter who owns the posting
DROP POLICY IF EXISTS application_status_history_select ON public.application_status_history;
CREATE POLICY application_status_history_select
  ON public.application_status_history FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.applications AS a
      JOIN public.jobs AS j ON j.id = a.job_id
      WHERE a.id = application_id
        AND (a.applicant_id = (SELECT auth.uid()) OR j.recruiter_id = (SELECT auth.uid()))
    )
  );

REVOKE ALL ON TABLE public.application_status_history FROM anon, authenticated;
GRANT SELECT ON TABLE public.application_status_history TO authenticated;
